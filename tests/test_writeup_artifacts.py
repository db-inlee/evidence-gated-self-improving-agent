def test_build_writes_every_file_deterministically(tmp_path: Path, values: dict[str, Any]) -> None:
    a = build_artifacts(values, tmp_path / "a")
    b = build_artifacts(values, tmp_path / "b")
    assert sorted(a) == sorted(FILES) and a == b
    for name in FILES:
        assert (tmp_path / "a" / name).read_bytes() == (tmp_path / "b" / name).read_bytes(), name
        assert a[name] == hashlib.sha256((tmp_path / "a" / name).read_bytes()).hexdigest()


def test_committed_artifacts_equal_a_rebuild(tmp_path: Path, values: dict[str, Any]) -> None:
    build_artifacts(values, tmp_path)
    manifest = (GENERATED / "artifacts.sha256").read_text().splitlines()
    recorded: dict[str, str] = {}
    for line in manifest:
        digest, name = line.split("  ")
        recorded[name] = digest
    assert sorted(recorded) == sorted(FILES)
    for name in FILES:
        committed = (GENERATED / name).read_bytes()
        assert committed == (tmp_path / name).read_bytes(), name
        assert recorded[name] == hashlib.sha256(committed).hexdigest()


def test_main_refuses_values_that_do_not_match_their_hash(tmp_path: Path) -> None:
    bad = tmp_path / "values.json"
    bad.write_bytes(VALUES.read_bytes() + b" ")
    (tmp_path / "values.json.sha256").write_text((GENERATED / "values.json.sha256").read_text())
    assert main(["--values", str(bad), "--out-dir", str(tmp_path / "out")]) == 1
    assert not (tmp_path / "out").exists()


