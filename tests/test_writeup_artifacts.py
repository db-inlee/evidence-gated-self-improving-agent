def templates(table: dict[str, Any]) -> list[str]:
    return [
        table["title"],
        table["note"],
        *table["columns"],
        *(c for row in table["rows"] for c in row),
    ]


def test_tables_are_t1_t2_t3(tables: dict[str, Any]) -> None:
    assert list(tables) == ["t1", "t2", "t3"]


@pytest.mark.parametrize("table_id", ["t1", "t2", "t3"])
def test_every_placeholder_resolves(
    tables: dict[str, Any], values: dict[str, Any], table_id: str
) -> None:
    keys = [k for t in templates(tables[table_id]) for k in PLACEHOLDER.findall(t)]
    assert keys
    assert [k for k in keys if k not in values] == []


@pytest.mark.parametrize("table_id", ["t1", "t2", "t3"])
def test_no_number_outside_placeholders(tables: dict[str, Any], table_id: str) -> None:
    for text in templates(tables[table_id]):
        bare = ALLOWED_NAME.sub("", PLACEHOLDER.sub("", text))
        assert not re.search(r"\d", bare), (table_id, text)


def test_fill_rejects_an_unknown_key(values: dict[str, Any]) -> None:
    with pytest.raises(KeyError, match=r"no\.such\.key"):
        fill("{{no.such.key}}", values)
    assert fill("C4: {{t005.rq.RQ1.verdict}}", values) == "C4: not supported"


def rendered_rows(table: dict[str, Any], values: dict[str, Any]) -> list[list[str]]:
    return [[fill(c, values) for c in row] for row in table["rows"]]


